#!/usr/bin/env node
/**
 * Appends per-page `Link` preload headers to dist/_headers: the page's stylesheets and the fonts it preloads, taken
 * from the built HTML (so the hashed file names are always the current ones).
 *
 * Why: Workers static assets don't turn <link rel="preload"> into headers (Pages does). With the zone's free Early
 * Hints setting on (Speed → Settings → Content Optimization), Cloudflare sends these as a 103 response before the
 * page, so the CSS and the LCP font start downloading one round trip earlier on a cold visit. Without that setting
 * the header is harmless: the browser dedupes it with the same <link rel="preload"> in the page.
 *
 * One rule per page path ("/", "/ar/cv/", …: exact matches; Workers allow 100 header rules, 2,000 characters a line).
 * `Link` appears in no other rule, so nothing is joined to it.
 *
 *   default export async ({ dist })   used by scripts/postbuild.mjs
 *   node scripts/postbuild/early-hints.mjs [--dist <dir>]
 */
import { appendFileSync, existsSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { pagePaths } from "./redirects.mjs";

const MARK = "# Early hints (generated by site/scripts/postbuild/early-hints.mjs)";

/**
 * The Link header value for one page's HTML, or "" when it has nothing to preload.
 * @param {string} html
 * @returns {string}
 */
export function linkHeader(html) {
  const head = html.slice(0, html.indexOf("</head>") + 1 || undefined);
  const attrs = (tag) => Object.fromEntries([...tag.matchAll(/\s([a-z-]+)(?:="([^"]*)")?/g)].map((m) => [m[1], m[2] ?? ""]));
  const links = [...head.matchAll(/<link\b[^>]*>/g)].map((m) => attrs(m[0]));
  const parts = [];
  for (const l of links) {
    if (l.rel === "stylesheet" && l.href?.startsWith("/_astro/")) parts.push(`<${l.href}>; rel=preload; as=style`);
    if (l.rel === "preload" && l.as === "font" && l.href?.startsWith("/_astro/"))
      parts.push(`<${l.href}>; rel=preload; as=font; type="font/woff2"; crossorigin`);
  }
  return [...new Set(parts)].join(", ");
}

export default async function earlyHints({ dist }) {
  const file = join(dist, "_headers");
  if (!existsSync(file)) throw new Error("early-hints: dist/_headers is missing");
  if (readFileSync(file, "utf8").includes(MARK)) return; // already appended (re-run on the same build)
  const blocks = [];
  for (const page of pagePaths(dist)) {
    const value = linkHeader(readFileSync(join(dist, page.slice(1), "index.html"), "utf8"));
    if (!value) continue;
    if (value.length > 1900) throw new Error(`early-hints: the Link header for ${page} is ${value.length} characters (limit 2,000 a line)`);
    blocks.push(`${page}\n  Link: ${value}`);
  }
  appendFileSync(file, `\n${MARK}\n${blocks.join("\n")}\n`);
  console.log(`early-hints: ${blocks.length} page rules in dist/_headers`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const i = args.indexOf("--dist");
  await earlyHints({ dist: resolve(i >= 0 ? args[i + 1] : fileURLToPath(new URL("../../../dist", import.meta.url))) });
}
