#!/usr/bin/env node
/**
 * Appends one header rule per page to dist/_headers, both values taken from the built HTML (so hashed file names and
 * CSP hashes are always the current ones):
 *
 * 1. `Link`: the page's stylesheets and the fonts it preloads. Workers static assets don't turn <link rel="preload">
 *    into headers (Pages does). With the zone's free Early Hints setting on (Speed → Settings → Content Optimization),
 *    Cloudflare sends these as a 103 response before the page, so the CSS and the LCP font start downloading one round
 *    trip earlier on a cold visit. Without that setting the header is harmless: the browser dedupes it with the same
 *    <link rel="preload"> in the page.
 * 2. `Content-Security-Policy-Report-Only`: the page's own <meta> policy (script-src/style-src with this page's
 *    hashes and the other fetch directives), with `report-uri` + `report-to csp` added (audit SEC-H01). A <meta>
 *    policy can't report, so on its own the per-page rules fail silently. The browser evaluates this mirror next to
 *    the <meta> from the first byte of the response and reports what the <meta> blocks through the Reporting API, with
 *    no script involved: violations raised while the HTML is parsed, an injected inline script, or the page's own boot
 *    script blocked after something rewrote it (a page-script listener would be blocked or late in exactly those
 *    cases). It enforces nothing, so it can't break a page. Left out: base-uri, form-action and object-src, which the
 *    enforced header policy in public/_headers already has and reports (each violation is counted once), and anything
 *    a <meta> ignores; and style attributes are not reported (a WebKit quirk, see MIRROR_ONLY). ~0.7 KB of response
 *    header per page view.
 *
 * One rule per page path ("/", "/ar/cv/", …: exact matches; Workers allow 100 header rules and 2,000 characters a
 * line). Neither header appears in another rule, so nothing is joined to them. The 404 pages are served for any path,
 * so they get no rule: their <meta> still enforces, silently.
 *
 *   default export async ({ dist })   used by scripts/postbuild.mjs
 *   node scripts/postbuild/early-hints.mjs [--dist <dir>]
 */
import { appendFileSync, existsSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { pagePaths } from "./redirects.mjs";

const MARK = "# Per-page headers: Early Hints Link + CSP Report-Only mirror (generated by site/scripts/postbuild/early-hints.mjs)";
/** Workers static assets: characters per _headers line. */
export const HEADER_LINE_LIMIT = 2000;
/** Directives the header policy (public/_headers) enforces and reports itself, or that a <meta> policy ignores. */
const NOT_MIRRORED = new Set(["base-uri", "form-action", "object-src", "frame-ancestors", "sandbox", "report-uri", "report-to", "style-src-attr"]);
/** Where the mirror reports (the same endpoint as the header policy; Reporting-Endpoints is set for every path). */
export const REPORT_DIRECTIVES = "report-uri /api/csp-report; report-to csp";
/**
 * Not reported: style attributes. WebKit checks the inline style of a <select>'s own user-agent shadow tree against
 * the page policy (tests/e2e/fixtures.ts), so every Safari visit to a page with the contact form would send a report
 * about the browser itself. The <meta> still enforces style-src for attributes, and the build fails on any style=""
 * attribute of ours (integrations/csp-hashes.mjs), so only this report is lost.
 */
const MIRROR_ONLY = "style-src-attr 'unsafe-inline'";

/**
 * The Link header value for one page's HTML, or "" when it has nothing to preload.
 * @param {string} html
 * @returns {string}
 */
export function linkHeader(html) {
  const head = html.slice(0, html.indexOf("</head>") + 1 || undefined);
  const attrs = (tag) => Object.fromEntries([...tag.matchAll(/\s([a-z-]+)(?:="([^"]*)")?/g)].map((m) => [m[1], m[2] ?? ""]));
  const links = [...head.matchAll(/<link\b[^>]*>/g)].map((m) => attrs(m[0]));
  const parts = [];
  for (const l of links) {
    if (l.rel === "stylesheet" && l.href?.startsWith("/_astro/")) parts.push(`<${l.href}>; rel=preload; as=style`);
    if (l.rel === "preload" && l.as === "font" && l.href?.startsWith("/_astro/"))
      parts.push(`<${l.href}>; rel=preload; as=font; type="font/woff2"; crossorigin`);
  }
  return [...new Set(parts)].join(", ");
}

/**
 * The Report-Only mirror of a page's CSP <meta>, or "" when the page has none.
 * @param {string} html
 * @returns {string}
 */
export function reportOnlyPolicy(html) {
  const metas = [...html.matchAll(/<meta http-equiv="content-security-policy" content="([^"]*)"\s*\/?>/gi)];
  if (metas.length !== 1) return "";
  const content = (metas[0]?.[1] ?? "").replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, "&");
  const kept = content
    .split(";")
    .map((d) => d.trim().replace(/\s+/g, " "))
    .filter((d) => d && !NOT_MIRRORED.has(d.split(" ")[0].toLowerCase()));
  if (!kept.some((d) => d.startsWith("script-src "))) throw new Error("early-hints: the CSP <meta> has no script-src to mirror");
  return [...kept, MIRROR_ONLY, REPORT_DIRECTIVES].join("; ");
}

export default async function earlyHints({ dist }) {
  const file = join(dist, "_headers");
  if (!existsSync(file)) throw new Error("early-hints: dist/_headers is missing");
  if (readFileSync(file, "utf8").includes(MARK)) return; // already appended (re-run on the same build)
  const blocks = [];
  let mirrored = 0;
  for (const page of pagePaths(dist)) {
    const html = readFileSync(join(dist, page.slice(1), "index.html"), "utf8");
    const lines = [];
    const link = linkHeader(html);
    if (link) lines.push(`  Link: ${link}`);
    const csp = reportOnlyPolicy(html);
    if (csp) {
      lines.push(`  Content-Security-Policy-Report-Only: ${csp}`);
      mirrored++;
    }
    for (const l of lines) if (l.length > HEADER_LINE_LIMIT) throw new Error(`early-hints: a header line for ${page} is ${l.length} characters (limit ${HEADER_LINE_LIMIT})`);
    if (lines.length) blocks.push(`${page}\n${lines.join("\n")}`);
  }
  appendFileSync(file, `\n${MARK}\n${blocks.join("\n")}\n`);
  console.log(`early-hints: ${blocks.length} page rules in dist/_headers (${mirrored} with the CSP Report-Only mirror)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const i = args.indexOf("--dist");
  await earlyHints({ dist: resolve(i >= 0 ? args[i + 1] : fileURLToPath(new URL("../../../dist", import.meta.url))) });
}
