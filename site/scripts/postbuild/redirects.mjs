#!/usr/bin/env node
/**
 * Writes dist/_redirects: permanent (301) redirects for URL forms people type or trim, generated from the built pages
 * so every new page is covered.
 *
 * Why: Workers static assets' html_handling ("auto-trailing-slash") answers "/cv" with a 307, a temporary redirect,
 * which search engines treat as a weak canonical signal; and "/work/" has no page. `_redirects` rules run before
 * html_handling and before asset lookup, match the exact path (case- and trailing-slash-sensitive, so "/cv/" never
 * matches "/cv" and there is no loop), keep the query string, and allow a fragment in the destination
 * (https://developers.cloudflare.com/workers/static-assets/redirects/; Free plan: 2,000 static rules). Requests that
 * run the Worker (/api/*) never see these rules.
 *
 * Rules, for every built page "/x/" (both locales):
 *   /x             /x/          301
 *   /x/index.html  /x/          301   (html_handling would 307 these too)
 * plus "/index.html / 301" and the /work/ parents → the home page's #work section (EN and AR).
 *
 *   default export async ({ dist })   used by scripts/postbuild.mjs (after relocate-404)
 *   node scripts/postbuild/redirects.mjs [--dist <dir>]
 */
import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * "/x/" for every dist/x/index.html (the root page included), sorted.
 * @param {string} dist
 * @returns {string[]}
 */
export function pagePaths(dist) {
  /** @type {string[]} */
  const out = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (name === "index.html") out.push(`/${relative(dist, dir).split(sep).filter(Boolean).join("/")}/`.replace(/^\/\/$/, "/"));
    }
  };
  walk(dist);
  return out.sort();
}

/**
 * @param {readonly string[]} pages page paths ("/x/")
 * @returns {[string, string][]} [from, to] pairs, all 301
 */
export function redirectRules(pages) {
  /** @type {[string, string][]} */
  const rules = [];
  for (const page of pages) {
    if (page !== "/") rules.push([page.slice(0, -1), page]);
    rules.push([`${page}index.html`, page]);
  }
  // The /work/ parent of the case studies has no page of its own: the list is the home page's "Selected work".
  for (const prefix of ["", "/ar"]) {
    if (pages.includes(`${prefix}/work/`)) continue;
    rules.push([`${prefix}/work`, `${prefix}/#work`], [`${prefix}/work/`, `${prefix}/#work`]);
  }
  return rules;
}

export default async function redirects({ dist }) {
  if (!existsSync(join(dist, "index.html"))) throw new Error(`redirects: no built site in ${dist}`);
  const rules = redirectRules(pagePaths(dist));
  const seen = new Set();
  for (const [from] of rules) {
    if (seen.has(from)) throw new Error(`redirects: duplicate rule for ${from}`);
    seen.add(from);
  }
  const width = Math.max(...rules.map(([from]) => from.length));
  const body = [
    "# Generated by site/scripts/postbuild/redirects.mjs: permanent redirects for slash-less and index.html URLs, and",
    "# for the /work/ parents. Exact paths only (all static rules). Don't edit by hand.",
    ...rules.map(([from, to]) => `${from.padEnd(width)}  ${to}  301`),
    "",
  ].join("\n");
  writeFileSync(join(dist, "_redirects"), body);
  console.log(`redirects: dist/_redirects (${rules.length} rules)`);
  return rules;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const i = args.indexOf("--dist");
  await redirects({ dist: resolve(i >= 0 ? args[i + 1] : fileURLToPath(new URL("../../../dist", import.meta.url))) });
}
