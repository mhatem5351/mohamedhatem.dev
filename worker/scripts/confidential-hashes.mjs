#!/usr/bin/env node
/**
 * Regenerates worker/src/chat/confidential-hashes.json, the hashed names the Worker's confidentiality guard blocks
 * (worker/src/chat/confidential.ts). Never prints a name.
 *
 *   canonical  copied from content/scripts/check-content.mjs (FORBIDDEN_SHA256), the repository-wide check
 *   variants   generated from the gitignored _inputs/forbidden-names.txt (KEY=phrase lines): every phrase of 1-3
 *              words, Arabic phrases also with a one- or two-letter prefix on the first word (و ف ب ل ك …), and every
 *              form also with Arabic letters folded (أ إ آ ٱ → ا, ة → ه, ى → ي). Longer phrases are eval placeholders
 *              only and are not hashed.
 *
 *   node worker/scripts/confidential-hashes.mjs           write the file
 *   node worker/scripts/confidential-hashes.mjs --check   exit 1 if the file is out of date (needs the names file)
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const namesFile = join(root, "_inputs", "forbidden-names.txt");
const outFile = join(root, "worker", "src", "chat", "confidential-hashes.json");
const check = process.argv.includes("--check");

if (!existsSync(namesFile)) {
  console.error("confidential-hashes: _inputs/forbidden-names.txt not found (local only, never committed); nothing to do.");
  process.exit(check ? 0 : 1);
}

const sha = (s) => createHash("sha256").update(s).digest("hex");
const words = (t) => t.normalize("NFKC").toLowerCase().replace(/\p{M}/gu, "").split(/[^\p{L}\p{N}]+/u).filter(Boolean);
const fold = (w) => w.replace(/[أإآٱ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي").replace(/ـ/g, "");
const ARABIC = /[؀-ۿ]/;
const PREFIXES = ["و", "ف", "ب", "ل", "ك", "ول", "وب", "فل", "فب", "وك"];

const phrases = readFileSync(namesFile, "utf8")
  .split(/\r?\n/)
  .map((l) => /^\s*[A-Z][A-Z0-9_]*\s*=\s*(.+?)\s*$/.exec(l)?.[1])
  .filter(Boolean)
  .map(words)
  .filter((w) => w.length >= 1 && w.length <= 3);

const all = new Set();
for (const p of phrases) {
  const forms = [p];
  if (ARABIC.test(p[0])) for (const pre of PREFIXES) forms.push([pre + p[0], ...p.slice(1)]);
  for (const f of forms) {
    all.add(sha(f.join(" ")));
    all.add(sha(f.map(fold).join(" ")));
  }
}

const checkContent = readFileSync(join(root, "content", "scripts", "check-content.mjs"), "utf8");
const canonical = [.../FORBIDDEN_SHA256\s*=\s*new Set\(\[([\s\S]*?)\]\)/.exec(checkContent)?.[1]?.matchAll(/[0-9a-f]{64}/g) ?? []].map((m) => m[0]);
const missing = canonical.filter((h) => !all.has(h)).length;
if (missing) console.warn(`confidential-hashes: ${missing} canonical hash(es) are not produced by the names file (kept anyway).`);
const variants = [...all].filter((h) => !canonical.includes(h)).sort();

const json =
  JSON.stringify(
    {
      about:
        "SHA-256 of normalised 1-3 word forms of the unnamed client's names (never the names). canonical = content/scripts/check-content.mjs FORBIDDEN_SHA256; variants = generated by worker/scripts/confidential-hashes.mjs from a gitignored file.",
      canonical,
      variants,
    },
    null,
    1,
  ) + "\n";

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current !== json) {
    console.error("confidential-hashes: worker/src/chat/confidential-hashes.json is out of date; run node worker/scripts/confidential-hashes.mjs");
    process.exit(1);
  }
  console.log(`confidential-hashes: up to date (${canonical.length} canonical + ${variants.length} variants)`);
} else {
  writeFileSync(outFile, json);
  console.log(`confidential-hashes: wrote ${canonical.length} canonical + ${variants.length} variant hashes`);
}
