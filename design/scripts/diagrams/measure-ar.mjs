#!/usr/bin/env node
// Measures the advance width of every label in the Arabic diagram variants (specs.mjs SPECS_AR, the Arabic legend)
// in Chromium, with the fonts the site serves: IBM Plex Sans Arabic 400 / 600 for Arabic code points, Inter for the
// rest (the same unicode ranges as site/astro.config.mjs). Arabic shaping makes per-character widths useless, so
// widths are stored per string, in em, for build.mjs (lib.mjs AR_EM). Run it after changing an Arabic label:
//
//   node design/scripts/diagrams/measure-ar.mjs      -> design/scripts/diagrams/metrics-ar.mjs
import fs from "node:fs";
import { chromium } from "@playwright/test";
import { SPECS_AR } from "./specs.mjs";
import { LEGEND } from "./captions.mjs";

const FONTS = new URL("../../../site/src/assets/fonts/", import.meta.url);
const ARABIC = "U+0600-065F, U+066A-066D, U+0670, U+200C-200F"; // site/astro.config.mjs ARABIC
const font = (file) => `url(data:font/woff2;base64,${fs.readFileSync(new URL(file, FONTS)).toString("base64")})`;

// weight -> strings: titles and tabs are 600, everything else 400 (lib.mjs css(), .dg-ar rules)
const want = { 600: new Set(), 400: new Set() };
const lines = (v) => (v ? String(v).split("\n") : []);
for (const variants of Object.values(SPECS_AR))
  for (const S of Object.values(variants)) {
    for (const n of S.nodes) {
      for (const t of lines(n.t)) want[600].add(t);
      for (const t of [...lines(n.s), ...lines(n.cap)]) want[400].add(t);
    }
    for (const g of S.groups ?? []) if (g.tab) want[600].add(g.tab);
    for (const t of S.texts ?? []) want[400].add(t.text);
    for (const e of S.edges ?? []) if (e.label) want[400].add(e.label);
  }
for (const v of Object.values(LEGEND)) want[400].add(v.ar);

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent(`<!doctype html><html lang="ar" dir="rtl"><head><style>
@font-face{font-family:"M Plex";src:${font("ibm-plex-sans-arabic-400-msa.woff2")} format("woff2");font-weight:400;unicode-range:${ARABIC}}
@font-face{font-family:"M Plex";src:${font("ibm-plex-sans-arabic-600-msa.woff2")} format("woff2");font-weight:600;unicode-range:${ARABIC}}
@font-face{font-family:"M Inter";src:${font("inter-latin-400-700.woff2")} format("woff2");font-weight:400 700}
span{font-family:"M Plex","M Inter";font-size:100px;white-space:pre;letter-spacing:0;font-kerning:normal}
</style></head><body></body></html>`);
const out = {};
for (const [weight, set] of Object.entries(want)) {
  out[weight] = await page.evaluate(
    async ([w, strs]) => {
      await document.fonts.load(`${w} 100px "M Plex"`, "ا");
      await document.fonts.load(`${w} 100px "M Inter"`, "a");
      const res = {};
      for (const s of strs) {
        const el = document.createElement("span");
        el.style.fontWeight = w;
        el.textContent = s;
        document.body.append(el);
        res[s] = Math.round((el.getBoundingClientRect().width / 100) * 1000) / 1000;
        el.remove();
      }
      return res;
    },
    [weight, [...set].sort()],
  );
}
const loaded = await page.evaluate(() => [...document.fonts].filter((f) => f.status === "loaded").map((f) => `${f.family} ${f.weight}`));
await browser.close();
if (loaded.length < 3) throw new Error(`fonts did not load: ${loaded.join(", ")}`);

fs.writeFileSync(
  new URL("metrics-ar.mjs", import.meta.url),
  `// Advance widths (em) of the Arabic diagram labels, by font weight. Generated by measure-ar.mjs; do not edit.\nexport const AR_EM = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`measured ${Object.values(out).reduce((a, o) => a + Object.keys(o).length, 0)} labels (${loaded.join(", ")})`);
