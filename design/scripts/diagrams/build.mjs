for (const theme of ["light", "dark"]) {
  const T = (k) => TOK[theme][`color-${k}`];
  const checks = [
    ["title on node", T("ink"), T("surface"), 4.5],
    ["sublabel on node", T("muted"), T("surface"), 4.5],
    ["group tab on canvas", T("muted"), T("bg"), 4.5],
    ["edge label on canvas", T("muted"), T("bg"), 4.5],
    ["thumb caption on canvas", T("ink-2"), T("bg"), 4.5],
    ["edge stroke on canvas", T("line-input"), T("bg"), 3],
    ["callout numeral on disc", "#14212B", T("saffron-fill"), 4.5],
    ...["teal", "saffron", "coral", "sky", "sage", "slate"].map((c) => [`${c} glyph on well`, T(c), T(`${c}-tint`), 3]),
  ];
  for (const [label, fg, bg, min] of checks) {
    const r = contrast(fg, bg);
    audit.push({ theme, label, ratio: Math.round(r * 100) / 100, min, ok: r >= min });
  }
}
const failed = audit.filter((a) => !a.ok);

