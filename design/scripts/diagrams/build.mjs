const STRICT = process.argv.includes("--strict");
const OUT = new URL("assets/diagrams/", DESIGN);
fs.mkdirSync(OUT, { recursive: true });

// ---------------------------------------------------------------- svgo (repo dependency first, then a local workspace)
async function loadSvgo() {
  try { return await import("svgo"); } catch { /* not installed in this repo yet */ }
  if (!process.env.SVGO_WORKSPACE) return null;
  try { return createRequire(`${process.env.SVGO_WORKSPACE}/package.json`)("svgo"); } catch { return null; }
}
const svgo = await loadSvgo();
const SVGO_CONFIG = {
  multipass: true,
  floatPrecision: 2,
  plugins: [{
    name: "preset-default",
    params: {
      overrides: {
        cleanupIds: false,          // ids are prefixed per diagram + variant and used by aria-labelledby
        removeDesc: false,          // <desc> is the screen-reader description
        inlineStyles: false,        // keep the themeable <style> block
        mergePaths: false,
        minifyStyles: { usage: false }, // keep opt-in classes (.dg-play) that are not in the markup
        removeUnknownsAndDefaults: { keepRoleAttr: true, keepAriaAttrs: true, unknownAttrs: false, defaultAttrs: false },
      },
    },
  }],
};
const optimise = (svg) => (svgo ? svgo.optimize(svg, SVGO_CONFIG).data : svg);

// ---------------------------------------------------------------- render
const VARIANTS = [["wide", ""], ["compact", "-compact"], ["thumb", "-thumb"]];
const results = [];
let warnings = 0;
for (const id of ORDER) {
  const spec = SPECS[id]; const cap = CAPTIONS[id];
  if (!spec || !cap) throw new Error(`missing spec or captions for ${id}`);
  for (const [variant, suffix] of VARIANTS) {
    if (!spec[variant]) continue;
    const desc = variant === "thumb" ? cap.desc.short.en : cap.desc.long.en;
    const d = new Diagram(spec[variant], { id, variant, title: cap.title.en, desc });
    const raw = d.render();
    for (const w of d.warn) { console.warn(`  warn ${id}/${variant}: ${w}`); warnings++; }
    const svg = optimise(raw);
    const file = `${id}${suffix}.svg`;
    fs.writeFileSync(new URL(file, OUT), svg);
    results.push({ id, variant, file, svg, w: spec[variant].w, h: spec[variant].h, bytes: Buffer.byteLength(svg), gzip: zlib.gzipSync(svg, { level: 9 }).length, br: zlib.brotliCompressSync(svg).length });
  }
}

