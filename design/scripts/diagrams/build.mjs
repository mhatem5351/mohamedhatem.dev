#!/usr/bin/env node
// Builds the case-study architecture diagrams from data.
//
//   node design/scripts/diagrams/build.mjs            -> assets/diagrams/*.svg, diagram.css, diagrams.json,
//                                                        prototypes/diagrams.html
//   node design/scripts/diagrams/build.mjs --strict   -> exit 1 on any layout warning (overflow, overlap, crossing)
//
// Sources: specs.mjs (geometry, labels), captions.mjs (EN/AR captions, callouts, descriptions),
// lib.mjs (renderer + styles), icons.mjs (glyphs shared with the UI icon set).
import fs from "node:fs";
